/**
 * The Objective-C source injected for Siri calls (`enableSiri`).
 *
 * Siri hands an app that lists `INStartCallIntent` in `INIntentsSupported` its
 * "call <name> with <app>" requests through the app delegate's
 * `application:handlerForIntent:` (in-app intent handling, iOS 14+; no
 * Intents extension). Expo's AppDelegate is Swift and regenerated on every
 * prebuild, so, as with the Recents forwarder, a separate Objective-C file adds
 * the method at runtime. It returns this package's `SWSiriCallIntentHandler`
 * (ios/SWSiriCallIntentHandler.m, autolinked), looked up by name so the file
 * builds without the pod's headers.
 *
 * The method wraps the delegate's own, if it has one: any other intent still
 * goes to the app.
 *
 * iOS asks the app delegate only in an app that supports multiple scenes
 * (`UIApplicationSupportsMultipleScenes`); the file logs it when the app does
 * not, since Siri then never reaches it and says nothing about why.
 */
export const SIRI_INTENT_SOURCE = `//
//  SignalWireSiriCallIntent.m
//
//  GENERATED by @signalwire/react-native's Expo config plugin.
//  Edits are overwritten on the next \`expo prebuild\`.
//
//  Hands Siri's INStartCallIntent ("call <name> with <app>") to
//  SWSiriCallIntentHandler. See docs/native-setup.md.
//

#import <Foundation/Foundation.h>
#import <Intents/Intents.h>
#import <objc/runtime.h>
#import <UIKit/UIKit.h>

typedef id (*SignalWireHandlerIMP)(id, SEL, UIApplication *, INIntent *);

static SignalWireHandlerIMP SignalWireOriginalHandler = NULL;

static id SignalWireHandlerForIntent(id self, SEL _cmd, UIApplication *application, INIntent *intent) {
  if ([intent isKindOfClass:[INStartCallIntent class]]) {
    Class handler = NSClassFromString(@"SWSiriCallIntentHandler");
    if (handler != Nil) {
      NSLog(@"[SignalWireSiri] Siri asked for a call; handing it to SWSiriCallIntentHandler");
      return [[handler alloc] init];
    }
    NSLog(@"[SignalWireSiri] SWSiriCallIntentHandler is missing: rebuild with @signalwire/react-native's pod");
  }
  return SignalWireOriginalHandler != NULL ? SignalWireOriginalHandler(self, _cmd, application, intent) : nil;
}

static void SignalWireInstallSiriHandler(Class cls) {
  static BOOL installed = NO;
  if (installed || cls == Nil) {
    return;
  }
  installed = YES;

  SEL selector = @selector(application:handlerForIntent:);
  // The class's own method, or one it inherits.
  Method existing = class_getInstanceMethod(cls, selector);
  const char *types = existing != NULL
                          ? method_getTypeEncoding(existing)
                          : protocol_getMethodDescription(@protocol(UIApplicationDelegate), selector, NO, YES).types;

  if (class_addMethod(cls, selector, (IMP)SignalWireHandlerForIntent, types)) {
    SignalWireOriginalHandler = existing != NULL ? (SignalWireHandlerIMP)method_getImplementation(existing) : NULL;
  } else {
    SignalWireOriginalHandler = (SignalWireHandlerIMP)method_setImplementation(
        class_getInstanceMethod(cls, selector), (IMP)SignalWireHandlerForIntent);
  }

  NSDictionary *scenes = [[NSBundle mainBundle] objectForInfoDictionaryKey:@"UIApplicationSceneManifest"];
  if (![scenes isKindOfClass:[NSDictionary class]] || ![scenes[@"UIApplicationSupportsMultipleScenes"] boolValue]) {
    NSLog(@"[SignalWireSiri] UIApplicationSupportsMultipleScenes is off: iOS will not ask this app for "
          @"Siri's call intents. See docs/native-setup.md.");
  }
  NSLog(@"[SignalWireSiri] handlerForIntent installed on %@", NSStringFromClass(cls));
}

@interface UIApplication (SignalWireSiriCallIntent)
@end

@implementation UIApplication (SignalWireSiriCallIntent)

+ (void)load {
  // Siri launches the app to resolve an intent; the delegate exists by the
  // time launching finishes, before iOS asks it for a handler.
  [[NSNotificationCenter defaultCenter]
      addObserverForName:UIApplicationDidFinishLaunchingNotification
                  object:nil
                   queue:[NSOperationQueue mainQueue]
              usingBlock:^(NSNotification *_Nonnull note) {
                SignalWireInstallSiriHandler([[UIApplication sharedApplication].delegate class]);
              }];
}

@end
`;
