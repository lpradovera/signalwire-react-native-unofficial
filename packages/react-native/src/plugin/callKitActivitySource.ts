/**
 * The Objective-C source injected for Recents and Siri call-backs.
 *
 * Tapping one of the app's calls in the Phone app's Recents, or asking Siri to
 * call back, opens the app with an `NSUserActivity` carrying an
 * `INStartCallIntent`. callkeep turns that into its `didReceiveStartCallAction`
 * event, but only if the app delegate hands it the activity:
 * `[RNCallKeep application:continueUserActivity:restorationHandler:]`.
 * Expo's AppDelegate is Swift, and Swift cannot import RNCallKeep
 * (react-native-callkeep#856), so — as with the PushKit hook — a separate
 * Objective-C file adds the forwarder at runtime instead of a patch to
 * `AppDelegate.swift`. `expo prebuild` regenerating the AppDelegate cannot
 * break it.
 *
 * The forwarder wraps the delegate's own method rather than replacing it:
 * universal links and Expo's subscribers still get every activity, and only
 * call intents go to callkeep. Under the UIScene lifecycle the scene delegate
 * must pass user activities to the app delegate's method (the example's
 * scene delegate does), which then reaches this forwarder.
 */
export const CALLKIT_ACTIVITY_SOURCE = `//
//  SignalWireCallKitActivity.m
//
//  GENERATED by @signalwire/react-native's Expo config plugin.
//  Edits are overwritten on the next \`expo prebuild\`.
//
//  Hands Recents and Siri call-backs (INStartCallIntent) to RNCallKeep, which
//  emits didReceiveStartCallAction to JavaScript. See docs/native-setup.md.
//

#import <Foundation/Foundation.h>
#import <Intents/Intents.h>
#import <objc/runtime.h>
#import <UIKit/UIKit.h>

#import "RNCallKeep.h"

typedef BOOL (*SignalWireContinueIMP)(id, SEL, UIApplication *, NSUserActivity *,
                                      void (^)(NSArray<id<UIUserActivityRestoring>> *));

static SignalWireContinueIMP SignalWireOriginalContinue = NULL;

static BOOL SignalWireIsCallActivity(NSUserActivity *activity) {
  NSString *type = activity.activityType;
  if ([type isEqualToString:@"INStartCallIntent"] || [type isEqualToString:@"INStartAudioCallIntent"] ||
      [type isEqualToString:@"INStartVideoCallIntent"]) {
    return YES;
  }
  return [activity.interaction.intent isKindOfClass:[INStartCallIntent class]];
}

static BOOL SignalWireContinueUserActivity(id self, SEL _cmd, UIApplication *application,
                                           NSUserActivity *activity,
                                           void (^handler)(NSArray<id<UIUserActivityRestoring>> *)) {
  BOOL handled = NO;
  if (SignalWireIsCallActivity(activity)) {
    NSLog(@"[SignalWireCallKit] call-back activity %@, handing it to RNCallKeep", activity.activityType);
    handled = [RNCallKeep application:application continueUserActivity:activity restorationHandler:handler];
  }
  BOOL original = SignalWireOriginalContinue != NULL
                      ? SignalWireOriginalContinue(self, _cmd, application, activity, handler)
                      : NO;
  return handled || original;
}

static void SignalWireInstallForwarder(Class cls) {
  static BOOL installed = NO;
  if (installed || cls == Nil) {
    return;
  }
  installed = YES;

  SEL selector = @selector(application:continueUserActivity:restorationHandler:);
  // The class's own method, or the one it inherits (ExpoAppDelegate has one).
  Method existing = class_getInstanceMethod(cls, selector);
  const char *types = existing != NULL
                          ? method_getTypeEncoding(existing)
                          : protocol_getMethodDescription(@protocol(UIApplicationDelegate), selector, NO, YES).types;

  if (class_addMethod(cls, selector, (IMP)SignalWireContinueUserActivity, types)) {
    // The class had no method of its own: call the inherited one, if any.
    SignalWireOriginalContinue = existing != NULL ? (SignalWireContinueIMP)method_getImplementation(existing) : NULL;
  } else {
    SignalWireOriginalContinue = (SignalWireContinueIMP)method_setImplementation(
        class_getInstanceMethod(cls, selector), (IMP)SignalWireContinueUserActivity);
  }
  NSLog(@"[SignalWireCallKit] continueUserActivity forwarder installed on %@", NSStringFromClass(cls));
}

@interface UIApplication (SignalWireCallKitActivity)
@end

@implementation UIApplication (SignalWireCallKitActivity)

+ (void)load {
  // Installed once the app delegate exists and before iOS delivers a launch
  // activity, which comes after didFinishLaunching (or, under scenes, when
  // the scene connects).
  [[NSNotificationCenter defaultCenter]
      addObserverForName:UIApplicationDidFinishLaunchingNotification
                  object:nil
                   queue:[NSOperationQueue mainQueue]
              usingBlock:^(NSNotification *_Nonnull note) {
                SignalWireInstallForwarder([[UIApplication sharedApplication].delegate class]);
              }];
}

@end
`;
