#!/usr/bin/env node
/**
 * Verifies the Expo config plugin against a real `expo prebuild`.
 *
 * The unit tests in `withSignalWire.test.ts` mock `withInfoPlist`, so they prove
 * the plugin's own logic but not that Expo's mod pipeline applies it. This runs
 * the real thing and asserts on the generated native files.
 *
 * Needs no Xcode, Android SDK, or CocoaPods — prebuild only generates sources.
 *
 * It prebuilds a scratch copy of example/ under .tmp/, never example/ itself:
 * `prebuild --clean` deletes the native projects it regenerates, and the ones in
 * example/ are the developer's (Pods, signing edits, google-services), built for
 * their own SW_APP_ID. `expo run:ios` reuses an existing ios/ as it is, so a
 * check that replaced them left the next device build on the placeholder app.
 *
 * Usage: node scripts/verify-prebuild.mjs
 */
import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, symlinkSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'example');
const scratch = join(root, '.tmp', 'verify-prebuild');
const example = join(scratch, 'example');

/** Generated by a prebuild or an install, or kept locally; none of it is input. */
const NOT_COPIED = new Set(['node_modules', 'ios', 'android', '.expo', '.expo-export-check']);

// A stand-in Firebase project file. GOOGLE_SERVICES_JSON is set for both
// prebuilds, as it is in a developer's environment once Android push is set
// up: Android must pick it up, and iOS must still prebuild with it set.
const GOOGLE_SERVICES_FIXTURE = join(root, 'scripts', 'fixtures', 'google-services.fixture.json');

const IOS_PLIST = 'ios/SignalWireRNExample/Info.plist';
const IOS_VOIP_SOURCE = 'ios/SignalWireRNExample/SignalWireVoipPush.m';
const IOS_PBXPROJ = 'ios/SignalWireRNExample.xcodeproj/project.pbxproj';
const IOS_ENTITLEMENTS = 'ios/SignalWireRNExample/SignalWireRNExample.entitlements';
const IOS_APP_DELEGATE = 'ios/SignalWireRNExample/AppDelegate.swift';
const ANDROID_MANIFEST = 'android/app/src/main/AndroidManifest.xml';
const ANDROID_APP_GRADLE = 'android/app/build.gradle';
const ANDROID_GOOGLE_SERVICES = 'android/app/google-services.json';

const EXPECTED_ANDROID_PERMISSIONS = [
  'android.permission.RECORD_AUDIO',
  'android.permission.CAMERA',
  'android.permission.MODIFY_AUDIO_SETTINGS',
  'android.permission.FOREGROUND_SERVICE',
  'android.permission.FOREGROUND_SERVICE_MICROPHONE',
  'android.permission.POST_NOTIFICATIONS',
  'android.permission.WAKE_LOCK',
  'android.permission.BIND_TELECOM_CONNECTION_SERVICE',
  'android.permission.MANAGE_OWN_CALLS',
  'android.permission.READ_PHONE_STATE'
];

const EXPECTED_PLIST_ENTRIES = [
  'NSMicrophoneUsageDescription',
  'NSCameraUsageDescription',
  '<string>audio</string>',
  '<string>voip</string>'
];

const failures = [];

function prepareScratchCopy() {
  rmSync(scratch, { recursive: true, force: true });
  mkdirSync(scratch, { recursive: true });
  cpSync(source, example, {
    recursive: true,
    filter: (path) => {
      const top = relative(source, path).split(sep)[0];
      // .env files hold the developer's own app id and endpoints; the check
      // runs on the committed configuration only.
      return top === '' || (!NOT_COPIED.has(top) && !top.startsWith('.env'));
    }
  });
  // The workspace's own nested dependencies. Everything else resolves from the
  // repository root's node_modules, which is an ancestor of .tmp/.
  if (existsSync(join(source, 'node_modules'))) {
    symlinkSync(join(source, 'node_modules'), join(example, 'node_modules'), 'dir');
  }
}

function prebuild(platform) {
  process.stdout.write(`  prebuild ${platform}… `);
  execFileSync('npx', ['expo', 'prebuild', '--platform', platform, '--no-install', '--clean'], {
    cwd: example,
    stdio: 'pipe',
    env: {
      ...process.env,
      GOOGLE_SERVICES_JSON: GOOGLE_SERVICES_FIXTURE,
      // Ignore the developer's example/.env, should one be found: the check is
      // about the committed configuration and the placeholder app id.
      EXPO_NO_DOTENV: '1'
    }
  });
  process.stdout.write('ok\n');
}

function check(label, contents, needles) {
  for (const needle of needles) {
    if (!contents.includes(needle)) {
      failures.push(`${label}: missing ${needle}`);
    }
  }
}

console.log('Verifying the Expo config plugin against a real prebuild:');

prepareScratchCopy();

prebuild('android');
check(
  ANDROID_MANIFEST,
  readFileSync(join(example, ANDROID_MANIFEST), 'utf8'),
  EXPECTED_ANDROID_PERMISSIONS
);
// Firebase is applied to Android only (example/plugins/withFirebaseAndroid.js).
check(ANDROID_APP_GRADLE, readFileSync(join(example, ANDROID_APP_GRADLE), 'utf8'), [
  'com.google.gms.google-services'
]);
if (!existsSync(join(example, ANDROID_GOOGLE_SERVICES))) {
  failures.push(`${ANDROID_GOOGLE_SERVICES}: not copied from GOOGLE_SERVICES_JSON`);
}

// Getting past this line is itself an iOS check: with GOOGLE_SERVICES_JSON set,
// applying Firebase's whole plugin failed here, demanding a
// GoogleService-Info.plist that an app using PushKit has no use for.
prebuild('ios');
check(IOS_PLIST, readFileSync(join(example, IOS_PLIST), 'utf8'), EXPECTED_PLIST_ENTRIES);
if (readFileSync(join(example, IOS_APP_DELEGATE), 'utf8').includes('FirebaseApp')) {
  failures.push(`${IOS_APP_DELEGATE}: Firebase configured on iOS, which uses PushKit`);
}

// The VoIP hook is native code that only runs if Xcode compiles it. Writing
// the file is not enough: an unreferenced .m is silently ignored, and the
// failure shows up much later as "pushes do nothing".
check(IOS_VOIP_SOURCE, readFileSync(join(example, IOS_VOIP_SOURCE), 'utf8'), [
  'PKPushRegistry',
  'reportNewIncomingCall',
  'call_id',
  'SignalWireVoipTokenNotification'
]);
check(IOS_PBXPROJ, readFileSync(join(example, IOS_PBXPROJ), 'utf8'), [
  'SignalWireVoipPush.m in Sources'
]);

// Without this, iOS issues no PushKit token and the failure is silent from the
// server: APNs keeps accepting pushes and reporting them delivered.
check(IOS_ENTITLEMENTS, readFileSync(join(example, IOS_ENTITLEMENTS), 'utf8'), [
  'aps-environment'
]);

// Injecting twice would make Xcode compile the translation unit twice and fail
// on duplicate symbols, so the mod must be idempotent across repeat prebuilds.
{
  const pbxproj = readFileSync(join(example, IOS_PBXPROJ), 'utf8');
  const occurrences = pbxproj.split('SignalWireVoipPush.m in Sources').length - 1;
  if (occurrences !== 2) {
    failures.push(
      `${IOS_PBXPROJ}: expected exactly 2 references to "SignalWireVoipPush.m in Sources" ` +
        `(one PBXBuildFile, one in the Sources phase), found ${occurrences}`
    );
  }
}

if (failures.length > 0) {
  console.error(`\n${failures.length} plugin assertion(s) failed (generated files kept in ${scratch}):`);
  for (const failure of failures) {
    console.error(`  ✗ ${failure}`);
  }
  process.exit(1);
}

rmSync(scratch, { recursive: true, force: true });

console.log(
  `\n✓ ${EXPECTED_ANDROID_PERMISSIONS.length} Android permissions, ` +
    `${EXPECTED_PLIST_ENTRIES.length} iOS Info.plist entries, the VoIP push ` +
    `hook (generated and compiled), and Firebase on Android only.`
);
